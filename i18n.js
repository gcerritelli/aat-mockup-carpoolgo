function t(clave, idioma) {
  const dict = traducciones[idioma] || traducciones[IDIOMA_DEFAULT];
  if (dict && dict[clave] != null) return dict[clave];
  return traducciones.es[clave] != null ? traducciones.es[clave] : clave;
}

function aplicarTraducciones(idioma) {
  document.documentElement.lang = idioma;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'), idioma);
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph'), idioma));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title'), idioma));
  });
}
